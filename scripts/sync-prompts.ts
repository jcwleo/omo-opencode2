import { mkdtemp, rm } from "node:fs/promises"
import { homedir, tmpdir } from "node:os"
import { join, resolve } from "node:path"

const PROJECT_ROOT = resolve(import.meta.dir, "..")
const VARIANTS_MODULE = join(PROJECT_ROOT, "src", "prompts", "model-variants.generated.js")
const DEFAULT_SENPI_REPO = join(homedir(), "Projects/omo-fork/senpi")
const DEFAULT_FORK_PACKAGES = join(homedir(), "Projects/omo-fork/oh-my-openagent/packages")

// Tool sets OpenCode 2.1.4 sends: GPT models get `patch` instead of `edit`/`write`, category lanes lose
// `subagent`/`question`, and `todowrite` appears only with `experimental.todo`.
const GPT_PRIMARY = ["execute", "glob", "grep", "patch", "question", "read", "shell", "skill", "subagent", "webfetch", "websearch"]
const OTHER_PRIMARY = ["edit", "execute", "glob", "grep", "question", "read", "shell", "skill", "subagent", "webfetch", "websearch", "write"]
const withoutDelegation = (tools: readonly string[]): string[] => tools.filter((tool) => tool !== "subagent" && tool !== "question")
const VALIDATION_TOOL_SETS: readonly (readonly string[])[] = [
  GPT_PRIMARY,
  OTHER_PRIMARY,
  withoutDelegation(GPT_PRIMARY),
  withoutDelegation(OTHER_PRIMARY),
  [...GPT_PRIMARY, "todowrite"],
  [...OTHER_PRIMARY, "todowrite"],
]

function flagValue(flag: string): string | undefined {
  const index = process.argv.indexOf(flag)
  if (index === -1) return undefined
  const value = process.argv[index + 1]
  if (value === undefined) throw new Error(`${flag} needs a directory`)
  return value
}

async function bundleModelVariants(presetDir: string, forkPackages: string): Promise<void> {
  const workDir = await mkdtemp(join(tmpdir(), "omo-opencode2-variants-"))
  try {
    const entry = join(workDir, "entry.ts")
    await Bun.write(
      entry,
      [
        `export { resolvePresetName } from ${JSON.stringify(join(presetDir, "contract.ts"))}`,
        `export { buildPreset } from ${JSON.stringify(join(presetDir, "presets.ts"))}`,
        `export { isGpt6AstraModel } from ${JSON.stringify(join(forkPackages, "model-core/src/model-family-detectors.ts"))}`,
        `import { BUILTIN_CATEGORY_DEFAULTS } from ${JSON.stringify(join(forkPackages, "senpi-task/src/category/builtins.ts"))}`,
        "export function categoryPromptAppend(category: string, modelId: string | undefined): string | undefined {",
        "  const definition = BUILTIN_CATEGORY_DEFAULTS.find((candidate) => candidate.name === category)",
        "  if (definition === undefined) return undefined",
        "  return (definition.resolvePromptAppend?.(modelId) ?? definition.promptAppend).trim()",
        "}",
        "",
      ].join("\n"),
    )
    const result = await Bun.build({ entrypoints: [entry], target: "bun", format: "esm" })
    if (!result.success) throw new Error(`bundling model variants failed:\n${result.logs.map(String).join("\n")}`)
    const output = result.outputs[0]
    if (output === undefined) throw new Error("bundling model variants produced no output")
    const header = "// Generated by scripts/sync-prompts.ts from senpi prompt-preset (MIT), oh-my-openagent model-core and senpi-task.\n"
    await Bun.write(VARIANTS_MODULE, header + (await output.text()))
  } finally {
    await rm(workDir, { recursive: true, force: true })
  }
}

async function validatePresets(presetDir: string): Promise<number> {
  const { VALID_PRESETS }: { VALID_PRESETS: ReadonlySet<string> } = await import(join(presetDir, "settings.ts"))
  const { renderPreset, PRESET_REWRITES, LEFTOVER_PATTERN } = await import("../src/prompts/presets.ts")
  const hits = new Map<(typeof PRESET_REWRITES)[number], number>()
  let renders = 0
  for (const name of [...VALID_PRESETS].filter((preset) => preset !== "auto")) {
    for (const toolSet of VALIDATION_TOOL_SETS) {
      const text = renderPreset(name, Object.fromEntries(toolSet.map((tool) => [tool, { description: "" }])), hits)
      const leftover = text.match(LEFTOVER_PATTERN)
      if (leftover !== null) throw new Error(`preset ${name} still mentions a Senpi-only tool: "${leftover[0]}"`)
      if (!toolSet.includes("edit") && text.includes("`edit` and `write`")) throw new Error(`preset ${name} names edit/write for a patch-only tool set`)
      if (text.includes("apply_patch")) throw new Error(`preset ${name} still names apply_patch`)
      renders++
    }
  }
  const unused = PRESET_REWRITES.filter((rewrite) => (hits.get(rewrite) ?? 0) === 0)
  if (unused.length > 0) throw new Error(`preset rewrites that matched nothing: ${unused.map((rewrite) => rewrite.pattern.source).join(" | ")}`)
  return renders
}

async function main(): Promise<void> {
  const senpiRepo = resolve(flagValue("--senpi-repo") ?? process.env.SENPI_REPO ?? DEFAULT_SENPI_REPO)
  const forkPackages = resolve(flagValue("--fork") ?? process.env.OMO_FORK_PACKAGES ?? DEFAULT_FORK_PACKAGES)
  const presetDir = join(senpiRepo, "packages/coding-agent/src/core/extensions/builtin/prompt-preset")

  await bundleModelVariants(presetDir, forkPackages)
  const renders = await validatePresets(presetDir)
  console.log(`bundled ${VARIANTS_MODULE}; validated ${renders} preset renders across ${VALIDATION_TOOL_SETS.length} tool sets`)
}

await main()
